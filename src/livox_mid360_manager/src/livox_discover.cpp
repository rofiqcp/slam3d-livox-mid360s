namespace fs = std::filesystem;

struct InterfaceAddress {
  std::string name;
  std::string ip;
  int prefix{24};
};

struct FoundLidar {
  std::string host_ip;
  std::string interface_name;
  std::string lidar_ip;
  std::string serial;
  uint8_t dev_type{0};
};

std::mutex g_mutex;
std::vector<FoundLidar> g_found;
std::string g_host_ip;
std::string g_interface;

static int prefix_from_mask(const sockaddr_in *mask) {
  if (!mask) return 24;
  uint32_t value = ntohl(mask->sin_addr.s_addr);
  int prefix = 0;
  while (value & 0x80000000U) {
    ++prefix;
    value <<= 1U;
  }
  return prefix;
}

static std::vector<InterfaceAddress> list_ipv4_interfaces(const std::string &only) {
  std::vector<InterfaceAddress> out;
  ifaddrs *ifaddr = nullptr;
  if (getifaddrs(&ifaddr) != 0) return out;

  for (ifaddrs *ifa = ifaddr; ifa != nullptr; ifa = ifa->ifa_next) {
    if (!ifa->ifa_addr || ifa->ifa_addr->sa_family != AF_INET) continue;
    if (!(ifa->ifa_flags & IFF_UP) || (ifa->ifa_flags & IFF_LOOPBACK)) continue;

    const std::string name = ifa->ifa_name;
    if (!only.empty() && only != "auto" && name != only) continue;
    if (name.rfind("docker", 0) == 0 || name.rfind("tailscale", 0) == 0 ||
        name.rfind("veth", 0) == 0 || name.rfind("br-", 0) == 0) {
      continue;
    }

    char buf[INET_ADDRSTRLEN] = {};
    auto *addr = reinterpret_cast<sockaddr_in *>(ifa->ifa_addr);
    inet_ntop(AF_INET, &addr->sin_addr, buf, sizeof(buf));
    auto *mask = reinterpret_cast<sockaddr_in *>(ifa->ifa_netmask);
    out.push_back({name, buf, prefix_from_mask(mask)});
  }
  freeifaddrs(ifaddr);

  std::stable_sort(out.begin(), out.end(), [](const auto &a, const auto &b) {
    const bool a_livox = a.ip.rfind("192.168.1.", 0) == 0;
    const bool b_livox = b.ip.rfind("192.168.1.", 0) == 0;
    return a_livox > b_livox;
  });
  return out;
}

static std::string model_name(uint8_t type) {
  switch (type) {
    case kLivoxLidarTypeMid360s: return "MID360S";
    case kLivoxLidarTypeMid360: return "MID360";
    case kLivoxLidarTypeAvia: return "AVIA";
    case kLivoxLidarTypeAvia2: return "AVIA2";
    case kLivoxLidarTypeHAP: return "HAP";
    case kLivoxLidarTypeIndustrialHAP: return "HAP_INDUSTRIAL";
    default: return "LIVOX_" + std::to_string(type);
  }
}

static void lidar_info_callback(const uint32_t, const LivoxLidarInfo *info, void *) {
  if (!info) return;

  FoundLidar f;
  f.host_ip = g_host_ip;
  f.interface_name = g_interface;
  f.lidar_ip = info->lidar_ip;
  f.serial = info->sn;
  f.dev_type = info->dev_type;

  std::lock_guard<std::mutex> lock(g_mutex);
  const auto duplicate = std::find_if(g_found.begin(), g_found.end(), [&](const auto &x) {
    return x.lidar_ip == f.lidar_ip && x.serial == f.serial;
  });
  if (duplicate == g_found.end()) {
    g_found.push_back(f);
    std::cout << "[FOUND] model=" << model_name(f.dev_type)
              << " lidar_ip=" << f.lidar_ip
              << " sn=" << f.serial
              << " via=" << f.interface_name << "/" << f.host_ip << std::endl;
  }
}

static std::string utc_now() {
  const auto now = std::chrono::system_clock::now();
  const std::time_t t = std::chrono::system_clock::to_time_t(now);
  std::tm tm{};
  gmtime_r(&t, &tm);
  std::ostringstream os;
  os << std::put_time(&tm, "%Y-%m-%dT%H:%M:%SZ");
  return os.str();
}

static void save_yaml(const std::string &path, const FoundLidar &f, int prefix) {
  const auto parent = fs::path(path).parent_path();
  if (!parent.empty()) fs::create_directories(parent);

  std::ofstream out(path);
  if (!out) throw std::runtime_error("cannot write " + path);

  out << "# Auto-generated by livox_discover. Safe to edit.\n";
  out << "device:\n";
  out << "  model: " << model_name(f.dev_type) << "\n";
  out << "  lidar_ip: " << f.lidar_ip << "\n";
  out << "  serial: \"" << f.serial << "\"\n";
  out << "  dev_type: " << static_cast<int>(f.dev_type) << "\n";
  out << "  discovered: true\n";
  out << "  last_seen_utc: \"" << utc_now() << "\"\n";
  out << "network:\n";
  out << "  interface: " << f.interface_name << "\n";
  out << "  host_ip: " << f.host_ip << "\n";
  out << "  prefix_length: " << prefix << "\n";
  out << "driver:\n";
  out << "  frame_id: livox_frame\n";
  out << "  publish_freq: 10.0\n";
  out << "  xfer_format: 0\n";
  out << "  point_topic: /livox/lidar\n";
  out << "  imu_topic: /livox/imu\n";
  out << "ports:\n";
  out << "  cmd_data_port: 56100\n";
  out << "  push_msg_port: 56200\n";
  out << "  point_data_port: 56300\n";
  out << "  imu_data_port: 56400\n";
  out << "  log_data_port: 56500\n";
  out << "  host_cmd_data_port: 56101\n";
  out << "  host_push_msg_port: 56201\n";
  out << "  host_point_data_port: 56301\n";
  out << "  host_imu_data_port: 56401\n";
  out << "  host_log_data_port: 56501\n";
}

int main(int argc, char **argv) {
  std::string interface = "auto";
  std::string explicit_host;
  std::string save_path;
  double timeout_s = 3.0;
  bool all = false;

  const char *explicit_config = std::getenv("LIVOX_MID360_CONFIG");
  const char *xdg = std::getenv("XDG_CONFIG_HOME");
  const char *home = std::getenv("HOME");
  if (explicit_config && *explicit_config) {
    save_path = explicit_config;
  } else if (xdg && *xdg) {
    save_path = std::string(xdg) + "/livox_mid360_manager/livox_runtime.yaml";
  } else if (home && *home) {
    save_path = std::string(home) + "/.config/livox_mid360_manager/livox_runtime.yaml";
  } else {
    save_path = "livox_runtime.yaml";
  }

  for (int i = 1; i < argc; ++i) {
    const std::string a = argv[i];
    auto need = [&](const char *opt) {
      if (i + 1 >= argc) throw std::runtime_error(std::string("missing value for ") + opt);
      return std::string(argv[++i]);
    };

    if (a == "--interface") interface = need("--interface");
    else if (a == "--host-ip") explicit_host = need("--host-ip");
    else if (a == "--timeout") timeout_s = std::stod(need("--timeout"));
    else if (a == "--save") save_path = need("--save");
    else if (a == "--all") all = true;
    else if (a == "-h" || a == "--help") {
      std::cout << "Usage: livox_discover [--interface auto|IFACE] [--host-ip IP] "
                   "[--timeout SEC] [--save YAML] [--all]\n";
      return 0;
    }
  }

  auto interfaces = list_ipv4_interfaces(interface);
  if (!explicit_host.empty()) {
    interfaces.erase(std::remove_if(interfaces.begin(), interfaces.end(),
      [&](const auto &x) { return x.ip != explicit_host; }), interfaces.end());

    if (interfaces.empty()) {
      interfaces.push_back({interface == "auto" ? "manual" : interface, explicit_host, 24});
    }
  }

  if (interfaces.empty()) {
    std::cerr << "No usable IPv4 interface found. Use --interface and/or --host-ip.\n";
    return 2;
  }

  std::cout << "Livox SDK2 discovery across " << interfaces.size() << " IPv4 address(es):\n";
  for (const auto &x : interfaces) {
    std::cout << "  " << x.name << " " << x.ip << "/" << x.prefix << "\n";
  }

  // SDK2 MID-360S requires a valid network JSON when handling device detection.
  // Passing nullptr caused a SIGSEGV inside GeneralCommandHandler::GetFirmwareType.
  // Reuse the same validated driver JSON, without changing the running ROS driver.
  const char *sdk_config_env = std::getenv("LIVOX_MID360_SDK_CONFIG");
  const std::string sdk_config = (sdk_config_env && *sdk_config_env)
      ? sdk_config_env
      : "/tmp/livox_mid360_manager/MID360s_runtime.json";
  if (!fs::is_regular_file(sdk_config)) {
    std::cerr << "Livox SDK configuration missing: " << sdk_config
              << "\nStart sensor.launch.py once or set LIVOX_MID360_SDK_CONFIG "
                 "to a valid MID360s JSON before SDK discovery.\n";
    return 4;
  }
  DisableLivoxSdkConsoleLogger();

  for (const auto &candidate : interfaces) {
    g_host_ip = candidate.ip;
    g_interface = candidate.name;

    if (!LivoxLidarSdkInit(sdk_config.c_str(), candidate.ip.c_str(), nullptr)) {
      std::cerr << "[WARN] SDK init failed on " << candidate.name << "/" << candidate.ip << "\n";
      continue;
    }

    SetLivoxLidarInfoChangeCallback(lidar_info_callback, nullptr);

    const auto until = std::chrono::steady_clock::now() +
      std::chrono::milliseconds(static_cast<int>(timeout_s * 1000.0));

    while (std::chrono::steady_clock::now() < until) {
      {
        std::lock_guard<std::mutex> lock(g_mutex);
        if (!g_found.empty() && !all) break;
      }
      std::this_thread::sleep_for(std::chrono::milliseconds(100));
    }

    LivoxLidarSdkUninit();

    std::lock_guard<std::mutex> lock(g_mutex);
    if (!g_found.empty() && !all) break;
  }

  FoundLidar selected;
  bool have = false;
  {
    std::lock_guard<std::mutex> lock(g_mutex);
    auto preferred = std::find_if(g_found.begin(), g_found.end(),
      [](const auto &f) {
        return f.dev_type == kLivoxLidarTypeMid360s ||
               f.dev_type == kLivoxLidarTypeMid360;
      });

    if (preferred != g_found.end()) {
      selected = *preferred;
      have = true;
    } else if (!g_found.empty()) {
      selected = g_found.front();
      have = true;
    }
  }

  if (!have) {
    std::cerr << "No Livox device discovered. Existing YAML is left unchanged.\n"
              << "If the LiDAR is on 192.168.1.0/24, first ensure the chosen "
                 "Ethernet/bridge/Wi-Fi interface owns a compatible host address "
                 "(recommended 192.168.1.10/24), then retry.\n";
    return 3;
  }

  int selected_prefix = 24;
  for (const auto &x : interfaces) {
    if (x.name == selected.interface_name && x.ip == selected.host_ip) {
      selected_prefix = x.prefix;
    }
  }

  save_yaml(save_path, selected, selected_prefix);
  std::cout << "Saved verified runtime configuration: " << save_path << "\n";
  return 0;
}
